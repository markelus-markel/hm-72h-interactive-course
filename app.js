  /* ----------------------------- Event handling ----------------------------- */

  function goToScreen(idx) {
    if (state.stop) return;
    if (idx < 0 || idx >= SCREENS.length) return;
    state.screenIdx = idx;
    render();
  }

  function handleClick(e) {
    var el = e.target.closest("[data-action]");
    if (!el) return;
    var action = el.getAttribute("data-action");

    if (state.stop && action !== "reset-demo") return; // hard block until reset

    switch (action) {
      case "go-prev": goToScreen(state.screenIdx - 1); break;
      case "go-next": goToScreen(state.screenIdx + 1); break;
      case "go-screen": goToScreen(parseInt(el.getAttribute("data-idx"), 10)); break;

      case "set-lang": {
        var lang = el.getAttribute("data-lang");
        if (lang === "ru" || lang === "kz") state.lang = lang;
        render();
        break;
      }

      case "set-gate-status": {
        var gate = el.getAttribute("data-gate");
        var status = el.getAttribute("data-status");
        state.gates[gate] = status;
        if (status === "STOP") triggerStop("gate-" + gate);
        render();
        break;
      }

      case "trigger-stop": triggerStop(el.getAttribute("data-source")); break;
      case "reset-demo": resetDemo(); break;
      case "toggle-teacher": state.teacherView = !state.teacherView; render(); break;

      case "select-object":
        state.objectType = el.getAttribute("data-object");
        state.artifacts.zoneMap = "DRAFT";
        render();
        break;

      case "toggle-zone": {
        var z = el.getAttribute("data-zone");
        var idx2 = state.zones.indexOf(z);
        if (idx2 === -1) state.zones.push(z); else state.zones.splice(idx2, 1);
        state.artifacts.routeChecklist = state.zones.length ? (state.zones.length >= 2 ? "SUBMITTED" : "DRAFT") : "NOT_STARTED";
        render();
        break;
      }

      case "select-system":
        state.selectedSystem = el.getAttribute("data-system");
        state.selectedComponentId = null;
        state.artifacts.sysCompTable = "DRAFT";
        render();
        break;

      case "select-component":
        state.selectedComponentId = el.getAttribute("data-component");
        state.artifacts.sysCompTable = "SUBMITTED";
        render();
        break;

      case "select-symptom":
        state.selectedSymptomId = el.getAttribute("data-symptom");
        state.artifacts.defectCards = state.artifacts.defectCards === "NOT_STARTED" ? "DRAFT" : state.artifacts.defectCards;
        render();
        break;

      case "select-photo":
        state.selectedPhoto = el.getAttribute("data-photo");
        state.uploadedPhotoDataUrl = null;
        state.artifacts.photoId = "SUBMITTED";
        render();
        break;

      case "submit-defect-card": submitDefectCard(); break;

      case "select-risk":
        state.lastRisk = el.getAttribute("data-risk");
        render();
        break;

      case "select-action":
        state.selectedAction = el.getAttribute("data-choice");
        if (state.selectedAction === "stop_now") { triggerStop("safe-action-choice"); return; }
        if (state.selectedAction === "neutral_message" && !state.neutralMessageText) state.neutralMessageText = defaultNeutralMessage();
        render();
        break;

      case "save-message": {
        var ta = document.getElementById("neutralMessageInput");
        if (ta) state.neutralMessageText = ta.value;
        state.artifacts.neutralMessage = "SUBMITTED";
        if (state.lastRisk && state.selectedAction) state.gates.G7 = "PASS";
        render();
        break;
      }

      case "generate-draft":
        state.actDraftText = generateActDraft();
        state.artifacts.actDraft = "DRAFT";
        render();
        break;

      case "save-draft": {
        var ta2 = document.getElementById("actDraftInput");
        if (ta2) state.actDraftText = ta2.value;
        state.artifacts.actDraft = "SUBMITTED";
        if (state.artifacts.defectStatement !== "NOT_STARTED") state.gates.G8 = "PASS";
        render();
        break;
      }

      case "save-self-report": {
        var ta3 = document.getElementById("selfReportInput");
        if (ta3) state.selfReportText = ta3.value;
        state.artifacts.selfReport = "SUBMITTED";
        render();
        break;
      }

      case "confirm-defense":
        state.defenseConfirmed = true;
        state.artifacts.finalDefense = "PASS";
        state.gates.G9 = "PASS";
        render();
        break;

      default: break;
    }
  }

  function handleChange(e) {
    var el = e.target;
    if (state.stop) return;

    if (el.matches('[data-action="set-artifact-status"]')) {
      state.artifacts[el.getAttribute("data-artifact")] = el.value;
      render();
      return;
    }
    if (el.id === "safetyCheckbox") return; // handled via handleCheckboxOrInput (also bound to 'change')
    if (el.id === "photoUploadInput") {
      var file = el.files && el.files[0];
      if (!file) return;
      var reader = new FileReader();
      reader.onload = function (ev) {
        state.uploadedPhotoDataUrl = ev.target.result;
        state.selectedPhoto = null;
        state.artifacts.photoId = "SUBMITTED";
        render();
      };
      reader.readAsDataURL(file);
      return;
    }
    if (el.id === "persistToggle") {
      try {
        if (el.checked) { localStorage.setItem(PERSIST_FLAG_KEY, "1"); localStorage.setItem(PERSIST_KEY, JSON.stringify(state)); }
        else { localStorage.setItem(PERSIST_FLAG_KEY, "0"); localStorage.removeItem(PERSIST_KEY); }
      } catch (e2) { /* ignore */ }
      return;
    }
  }

  function handleCheckboxOrInput(e) {
    var el = e.target;
    if (state.stop) return;
    if (el.id === "safetyCheckbox") {
      state.safetyAccepted = el.checked;
      state.artifacts.safetyLog = el.checked ? "SUBMITTED" : "NOT_STARTED";
      if (el.checked) state.gates.G0 = "PASS";
      render();
    }
    if (el.matches('[data-action="input-symptom-note"]')) {
      state.symptomNote = el.value;
      // no re-render needed on every keystroke to keep caret stable; state is enough
    }
  }

  function submitDefectCard() {
    var fact = (document.getElementById("cardFactInput") || {}).value || "";
    var hypothesis = (document.getElementById("cardHypothesisInput") || {}).value || "";
    var risk = (document.getElementById("cardRiskInput") || {}).value || "";
    var actionChoice = (document.getElementById("cardActionInput") || {}).value || "";
    var status = (document.getElementById("cardStatusInput") || {}).value || "DRAFT";

    var card = {
      id: "DC-" + String(state.cardIdCounter).padStart(3, "0"),
      zoneIds: state.zones.slice(),
      systemId: state.selectedSystem,
      componentId: state.selectedComponentId,
      signId: state.selectedSymptomId,
      photoRef: state.selectedPhoto || (state.uploadedPhotoDataUrl ? "__LOCAL_FILE__" : null),
      fact: fact || state.symptomNote || "",
      hypothesis: hypothesis,
      risk: risk || null,
      action: actionChoice || null,
      status: status
    };
    state.defectCards.push(card);
    state.cardIdCounter++;
    if (risk) state.lastRisk = risk;
    if (actionChoice) state.selectedAction = actionChoice;

    state.artifacts.defectCards = state.defectCards.length >= 3 ? "SUBMITTED" : "DRAFT";
    state.gates.G6 = "PASS";
    render();
  }

  function triggerStop(source) {
    state.stop = true;
    state.stopSource = source;
    state.artifacts.safetyLog = "BLOCKED";
    render();
  }

  function resetDemo() {
    var keepPersistPref = localStorage.getItem(PERSIST_FLAG_KEY) === "1";
    var keepLang = state.lang;
    state = defaultState();
    state.lang = keepLang; // language preference is not part of "progress" — keep current language on reset
    try {
      if (keepPersistPref) localStorage.setItem(PERSIST_KEY, JSON.stringify(state));
      else localStorage.removeItem(PERSIST_KEY);
    } catch (e) { /* ignore */ }
    render();
  }

